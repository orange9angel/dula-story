#!/usr/bin/env python3
"""Compile source choreography and explicit release edits from the same .story."""
from pathlib import Path
import hashlib
import json
import re

EP = Path(__file__).resolve().parents[1]
CAST = {'Xiaozao':'xiaozao', 'Jianwang':'jianwang', 'Weihe':'weihe'}

def stamp(s):
    h, m, sec, ms = map(int, re.split('[:,]', s))
    return h*3600+m*60+sec+ms/1000

def compile_story():
    source = EP/'script.story'
    text = source.read_text(encoding='utf-8-sig')
    blocks = re.split(r'\n\s*\n', text.strip())
    segments, lines, cues, edits = [], [], {}, []
    prev_end = 0
    for i, block in enumerate(blocks, 1):
        rows = block.strip().splitlines()
        assert int(rows[0]) == i, f'entry number {i}'
        a, b = rows[1].split(' --> ')
        start, end = stamp(a), stamp(b)
        assert start >= prev_end and end > start, f'overlap at entry {i}'
        prev_end = end
        body = '\n'.join(rows[2:])
        act = None
        for tag in re.findall(r'\{Event:([^}]+)\}', body):
            kind, *fields = tag.split('|')
            opts = dict(f.split('=',1) for f in fields)
            if kind == 'Beat':
                segments.append(dict(opts, start=start, kind='action', character=None))
            elif kind == 'Cue':
                name = opts['name']
                assert name not in cues, f'duplicate cue {name}'
                cues[name] = round(start+float(opts.get('offset', 0)), 3)
            elif kind == 'Act':
                act = opts
            elif kind == 'EditCut':
                a = round(start+float(opts['offset']), 3)
                b = round(a+float(opts['duration']), 3)
                assert a >= start and b > a
                edits.append({'id':opts['id'], 'start':a, 'end':b, 'reason':opts['reason']})
            else:
                raise ValueError(f'unhandled viewer event {kind}')
        spoken = re.findall(r'\[([A-Za-z]+)\]([^\n]+)', body)
        assert len(spoken) <= 1
        if spoken:
            who, words = spoken[0]
            assert act and who in CAST, f'missing direction at {i}'
            lines.append({'id':act['id'], 't':start, 'end':end, 'speaker':CAST[who],
                          'text':words.strip(),
                          'delivery':{'rate':int(act.get('rate',0)), 'context':act['context']},
                          'acting':{k:v for k,v in act.items() if k not in ['id','rate','context']}})
    assert segments[0]['start'] == 0 and lines
    for i, seg in enumerate(segments):
        seg['end'] = segments[i+1]['start'] if i+1 < len(segments) else prev_end
        assert seg['end'] > seg['start']
    assert len({l['id'] for l in lines}) == len(lines)
    assert all(0 <= t <= prev_end for t in cues.values())
    edits.sort(key=lambda x:x['start'])
    for i, edit in enumerate(edits):
        assert edit['end'] <= prev_end
        assert not i or edits[i-1]['end'] <= edit['start']
        assert not any(edit['start'] <= t < edit['end'] for t in cues.values()), 'cut removes story cue'
        assert all(abs(t*30-round(t*30)) < 1e-6 for t in (edit['start'],edit['end'])), 'cut must be frame aligned'
    source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
    voice = json.loads((EP/'config/voices.json').read_text(encoding='utf-8-sig'))
    def write(name, obj):
        (EP/'config'/name).write_text(json.dumps(obj, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    write('timeline.json', {'duration':prev_end, 'step':0.01, 'source':'script.story',
                           'source_sha256':source_hash, 'segments':segments})
    write('dialogue.json', dict(voice, source='script.story', source_sha256=source_hash, lines=lines))
    write('event_times.json', cues)
    write('editorial_cuts.json', {'source':'script.story', 'source_sha256':source_hash,
          'sourceDuration':prev_end, 'duration':round(prev_end-sum(x['end']-x['start'] for x in edits),3),
          'cuts':edits})
    (EP/'config/event_times.js').write_text('// Generated by tools/compile_story.py from script.story.\nexport const T = '+json.dumps(cues, indent=2)+';\nexport const B = '+json.dumps({s['id']:s['start'] for s in segments},indent=2)+';\n', encoding='utf-8')
    print(json.dumps({'duration':prev_end, 'segments':len(segments), 'lines':len(lines), 'cues':len(cues)}))

if __name__ == '__main__':
    compile_story()
